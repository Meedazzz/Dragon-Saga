const BrinDocumentPage: React.FC = () => {
  const { documentId } = useParams<{ documentId: string }>();
  const navigate = useNavigate();
  const documentInfo = documentId ? documents[documentId] : undefined;

  if (!documentInfo) {
    return (
      <Layout theme={brinTheme}>
        <main className="document-page">
          <HeroNav theme={brinTheme} characterId="brin" />
          <section className="document-hero-card">
            <h1>Документ не найден</h1>
            <p>В архиве Брина нет такого материала.</p>
            <button type="button" className="codex-btn codex-btn--primary tarot-no-glow" onClick={() => navigate('/brin')}>Вернуться к Брину</button>
          </section>
        </main>
      </Layout>
    );
  }

  return (
    <Layout theme={brinTheme} particleVariant="mixed" particleCount={22}>
      <main className="document-page document-page--article">
        <HeroNav theme={brinTheme} characterId="brin" />

        <motion.section className="document-hero-card" initial={{ opacity: 0, y: 18 }} animate={{ opacity: 1, y: 0 }}>
          <span className="codex-kicker">Материалы Брина</span>
          <h1>{documentInfo.title}</h1>
          <p className="document-subtitle">{documentInfo.subtitle}</p>
          <p>{documentInfo.description}</p>
        </motion.section>

        <div className="document-article-grid">
          {documentInfo.sections.map((section, index) => (
            <motion.article
              key={section.title}
              className="document-article-card"
              initial={{ opacity: 0, y: 16 }}
              whileInView={{ opacity: 1, y: 0 }}
              viewport={{ once: true, margin: '-80px' }}
              transition={{ delay: index * 0.035 }}
            >
              <h2>{section.title}</h2>
              {section.paragraphs?.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
              {section.bullets && (
                <ul>
                  {section.bullets.map((bullet) => <li key={bullet}>{bullet}</li>)}
                </ul>
              )}
            </motion.article>
          ))}
        </div>

        <section className="document-source-note">
          <p>Оригинальный PDF сохранён как источник, но основная страница оформлена как статья сайта.</p>
          <a href={documentInfo.file} target="_blank" rel="noopener noreferrer">Открыть исходный PDF</a>
          <a href={documentInfo.file} download>Скачать PDF</a>
        </section>
      </main>
    </Layout>
  );
};

export default BrinDocumentPage;
